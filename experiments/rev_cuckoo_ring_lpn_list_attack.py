"""Reduced leakage-weighted meet-in-the-middle Ring-LPN decoder.

The experiment keeps four regular error polynomials and the complete ideal
Reverse-Cuckoo leakage generated by four known regular polynomials.  Candidate
polynomials are scored independently because the ideal cross-product leakage
factors by the hidden-polynomial index.  Two candidate polynomials are then
combined on each side of the Ring-LPN equation.  A best-first Cartesian-list
generator emits pair sums in decreasing additive leakage score, and the two
sides are joined by their complete prime-field syndrome.

This is an actual reduced decoder: work is the number of per-polynomial
candidates scored plus the number of pair-list entries generated before an
equation solution is found.  It remains deliberately optimistic about sorting,
heap, and exact-matching evaluation costs, which are reported separately from
the merge-entry count.
"""

from __future__ import annotations

import argparse
import csv
import heapq
import itertools
import math
import random
import statistics
import time
from dataclasses import dataclass
from pathlib import Path

from rev_cuckoo_full_lpn_field import negacyclic_product
from rev_cuckoo_regular_isd import collision_pair_count, fit_pair_slope
from rev_cuckoo_regular_noise import (
    Descriptor,
    LeakageChannel,
    support_lists_one_unknown,
)


Candidate = tuple[int, ...]
Syndrome = bytes


@dataclass(frozen=True)
class CandidateEntry:
    index: int
    offsets: Candidate
    contribution: Syndrome
    pair_score: float
    exact_score: float


@dataclass(frozen=True)
class PairEntry:
    contribution: Syndrome
    left_index: int
    right_index: int


@dataclass(frozen=True)
class PartialCollisionFactor:
    """One matching factor represented for incremental support insertion."""

    items: tuple[tuple[int, ...], ...]
    labels: tuple[tuple[tuple[int, ...], ...], ...]


@dataclass(frozen=True)
class PrefixCandidate:
    offsets: Candidate
    pair_score: float


@dataclass(frozen=True)
class BeamSearchResult:
    candidates: tuple[PrefixCandidate, ...]
    generated_children: int


@dataclass(frozen=True)
class DecodeResult:
    selector: str
    candidate_scores: int
    merge_entries: int
    rounds: int
    recovered_planted: bool
    solution_count_lower_bound: int

    @property
    def optimistic_work(self) -> int:
        return self.candidate_scores + self.merge_entries


@dataclass(frozen=True)
class TrialResult:
    trial: int
    selector: str
    candidate_scores: int
    merge_entries: int
    rounds: int
    optimistic_work: int
    leakage_factor_evaluations: int
    factor_charged_work: int
    recovered_planted: int
    solution_count_lower_bound: int


def add_syndromes(left: Syndrome, right: Syndrome, modulus: int) -> Syndrome:
    return bytes((a + b) % modulus for a, b in zip(left, right))


def subtract_syndromes(
    left: Syndrome, right: Syndrome, modulus: int
) -> Syndrome:
    return bytes((a - b) % modulus for a, b in zip(left, right))


def regular_poly_field(
    offsets: Candidate, block_length: int, modulus: int
) -> tuple[int, ...]:
    values = [0] * (len(offsets) * block_length)
    for block, offset in enumerate(offsets):
        values[block * block_length + offset] = 1 % modulus
    return tuple(values)


def polynomial_contribution(
    offsets: Candidate,
    polynomial: int,
    multipliers: tuple[tuple[int, ...], ...],
    block_length: int,
    modulus: int,
) -> Syndrome:
    error = regular_poly_field(offsets, block_length, modulus)
    if polynomial == 0:
        return bytes(error)
    return bytes(
        negacyclic_product(multipliers[polynomial - 1], error, modulus)
    )


def descriptors_for_hidden(
    descriptors: tuple[Descriptor, ...],
    hidden: int,
    polys: int,
    weight: int,
) -> tuple[Descriptor, ...]:
    return tuple(
        descriptors[(known * polys + hidden) * weight + output]
        for known in range(polys)
        for output in range(weight)
    )


def pair_surrogate_score(
    active_lists: tuple[tuple[int, ...], ...],
    descriptors: tuple[Descriptor, ...],
    slope: float,
) -> float:
    return slope * sum(
        collision_pair_count(active, descriptor)
        for active, descriptor in zip(active_lists, descriptors)
    )


def partial_collision_factors(
    known: tuple[int, ...],
    descriptors: tuple[Descriptor, ...],
    polys: int,
    weight: int,
    block_length: int,
) -> tuple[PartialCollisionFactor, ...]:
    """Compile the pair-collision surrogate for prefix scoring.

    Every complete factor contains one item for each unknown offset.  Adding
    an offset either repeats an already active item, contributing nothing, or
    inserts a new active item whose label collisions with the distinct prior
    items can be counted immediately.  Consequently the accumulated collision
    count is monotone.  Since the fitted slope is non-positive, a prefix score
    is an upper bound on every completion of that prefix.
    """

    factors = []
    for known_poly in range(polys):
        for output in range(weight):
            descriptor = descriptors[known_poly * weight + output]
            items = []
            labels = [[None] * weight for _ in descriptor]
            for variable in range(weight):
                known_block = (output - variable) % weight
                base = known[known_poly * weight + known_block]
                variable_items = tuple(
                    base + value for value in range(block_length)
                )
                items.append(variable_items)
                for partition, partition_labels in enumerate(descriptor):
                    labels[partition][variable] = tuple(
                        partition_labels[item] for item in variable_items
                    )
            factors.append(
                PartialCollisionFactor(
                    items=tuple(items),
                    labels=tuple(
                        tuple(variable_labels)
                        for variable_labels in labels
                    ),
                )
            )
    return tuple(factors)


def extension_collision_count(
    prefix: Candidate,
    value: int,
    factors: tuple[PartialCollisionFactor, ...],
) -> int:
    """Return collisions introduced by appending one variable assignment."""

    variable = len(prefix)
    collisions = 0
    for factor in factors:
        item = factor.items[variable][value]
        prior_items: dict[int, int] = {}
        duplicate = False
        for prior_variable, prior_value in enumerate(prefix):
            prior_item = factor.items[prior_variable][prior_value]
            if prior_item == item:
                duplicate = True
                break
            prior_items.setdefault(prior_item, prior_variable)
        if duplicate:
            continue
        for prior_item, prior_variable in prior_items.items():
            prior_value = prefix[prior_variable]
            for partition in range(len(factor.labels)):
                collisions += (
                    factor.labels[partition][variable][value]
                    == factor.labels[partition][prior_variable][prior_value]
                )
    return collisions


def pair_beam_candidates(
    factors: tuple[PartialCollisionFactor, ...],
    weight: int,
    block_length: int,
    pair_slope: float,
    beam_width: int,
    output_count: int,
    rng: random.Random,
) -> BeamSearchResult:
    """Generate high-scoring supports with a bounded blockwise beam.

    The beam is deliberately a search heuristic, not an exact posterior
    sampler.  Prefixes are ranked by the monotone pair-collision upper bound;
    callers may evaluate and rerank the completed supports with the exact
    Reverse-Cuckoo likelihood.
    """

    if pair_slope > 0.0:
        raise ValueError("the collision upper bound requires a non-positive slope")
    if min(beam_width, output_count) < 1:
        raise ValueError("beam width and output count must be positive")
    beam = [(0.0, rng.random(), ())]
    generated_children = 0
    for _ in range(weight):
        children = []
        for score, _, prefix in beam:
            for value in range(block_length):
                collisions = extension_collision_count(prefix, value, factors)
                children.append(
                    (
                        score + pair_slope * collisions,
                        rng.random(),
                        prefix + (value,),
                    )
                )
        generated_children += len(children)
        keep = min(beam_width, len(children))
        beam = heapq.nlargest(keep, children, key=lambda item: (item[0], item[1]))
    beam.sort(key=lambda item: (item[0], item[1]), reverse=True)
    return BeamSearchResult(
        candidates=tuple(
            PrefixCandidate(offsets, score)
            for score, _, offsets in beam[:output_count]
        ),
        generated_children=generated_children,
    )


def build_candidate_lists(
    candidates: tuple[Candidate, ...],
    known: tuple[int, ...],
    descriptors: tuple[Descriptor, ...],
    multipliers: tuple[tuple[int, ...], ...],
    polys: int,
    weight: int,
    block_length: int,
    modulus: int,
    channel: LeakageChannel,
    pair_slope: float,
) -> tuple[tuple[CandidateEntry, ...], ...]:
    result = []
    for hidden in range(polys):
        hidden_descriptors = descriptors_for_hidden(
            descriptors, hidden, polys, weight
        )
        entries = []
        for index, candidate in enumerate(candidates):
            active_lists = support_lists_one_unknown(
                known, candidate, polys, weight
            )
            entries.append(
                CandidateEntry(
                    index=index,
                    offsets=candidate,
                    contribution=polynomial_contribution(
                        candidate,
                        hidden,
                        multipliers,
                        block_length,
                        modulus,
                    ),
                    pair_score=pair_surrogate_score(
                        active_lists,
                        hidden_descriptors,
                        pair_slope,
                    ),
                    exact_score=channel.candidate_log_weight(
                        active_lists, hidden_descriptors
                    ),
                )
            )
        result.append(tuple(entries))
    return tuple(result)


def selector_score(entry: CandidateEntry, selector: str) -> float:
    if selector == "pair":
        return entry.pair_score
    if selector == "exact":
        return entry.exact_score
    if selector == "uniform":
        return 0.0
    raise ValueError(f"unknown selector: {selector}")


class AffinePairGenerator:
    """A constant-memory random permutation of one Cartesian product."""

    def __init__(
        self,
        left: tuple[CandidateEntry, ...],
        right: tuple[CandidateEntry, ...],
        modulus: int,
        rng: random.Random,
    ) -> None:
        if len(left) != len(right):
            raise ValueError("uniform pair generator requires equal list sizes")
        self.left = left
        self.right = right
        self.modulus = modulus
        self.width = len(left)
        self.size = self.width * self.width
        self.offset = rng.randrange(self.size)
        while True:
            multiplier = rng.randrange(1, self.size)
            if math.gcd(multiplier, self.size) == 1:
                self.multiplier = multiplier
                break
        self.position = 0

    def __iter__(self):
        return self

    def __next__(self) -> PairEntry:
        if self.position >= self.size:
            raise StopIteration
        flat = (self.offset + self.multiplier * self.position) % self.size
        self.position += 1
        left_index, right_index = divmod(flat, self.width)
        left = self.left[left_index]
        right = self.right[right_index]
        return PairEntry(
            add_syndromes(left.contribution, right.contribution, self.modulus),
            left.index,
            right.index,
        )


class ScoredPairGenerator:
    """Best-first traversal of a monotone additive-score matrix."""

    def __init__(
        self,
        left: tuple[CandidateEntry, ...],
        right: tuple[CandidateEntry, ...],
        selector: str,
        modulus: int,
        rng: random.Random,
    ) -> None:
        def ordered(entries: tuple[CandidateEntry, ...]) -> tuple[tuple[float, CandidateEntry], ...]:
            scored = []
            for entry in entries:
                score = selector_score(entry, selector)
                if not math.isfinite(score):
                    score = -1e300
                scored.append((score + rng.random() * 1e-12, entry))
            scored.sort(key=lambda item: item[0], reverse=True)
            return tuple(scored)

        self.left = ordered(left)
        self.right = ordered(right)
        self.modulus = modulus
        self.heap = [
            (-(self.left[0][0] + self.right[0][0]), rng.random(), 0, 0)
        ]
        self.visited = {(0, 0)}
        self.rng = rng

    def __iter__(self):
        return self

    def __next__(self) -> PairEntry:
        if not self.heap:
            raise StopIteration
        _, _, left_index, right_index = heapq.heappop(self.heap)
        for following in (
            (left_index + 1, right_index),
            (left_index, right_index + 1),
        ):
            if (
                following[0] < len(self.left)
                and following[1] < len(self.right)
                and following not in self.visited
            ):
                self.visited.add(following)
                score = (
                    self.left[following[0]][0]
                    + self.right[following[1]][0]
                )
                heapq.heappush(
                    self.heap,
                    (-score, self.rng.random(), following[0], following[1]),
                )
        left = self.left[left_index][1]
        right = self.right[right_index][1]
        return PairEntry(
            add_syndromes(left.contribution, right.contribution, self.modulus),
            left.index,
            right.index,
        )


def pair_generator(
    left: tuple[CandidateEntry, ...],
    right: tuple[CandidateEntry, ...],
    selector: str,
    modulus: int,
    rng: random.Random,
):
    if selector == "uniform":
        return AffinePairGenerator(left, right, modulus, rng)
    return ScoredPairGenerator(left, right, selector, modulus, rng)


def decode_lists(
    candidate_lists: tuple[tuple[CandidateEntry, ...], ...],
    target: Syndrome,
    true_indices: tuple[int, ...],
    selector: str,
    modulus: int,
    rng: random.Random,
) -> DecodeResult:
    if len(candidate_lists) != 4:
        raise ValueError("the first list decoder supports exactly four polynomials")
    left_generator = pair_generator(
        candidate_lists[0], candidate_lists[1], selector, modulus, rng
    )
    right_generator = pair_generator(
        candidate_lists[2], candidate_lists[3], selector, modulus, rng
    )
    left_table: dict[Syndrome, PairEntry] = {}
    right_table: dict[Syndrome, PairEntry] = {}
    merge_entries = 0
    rounds = 0
    solution_count_lower_bound = 0
    while True:
        rounds += 1
        try:
            left = next(left_generator)
        except StopIteration:
            break
        merge_entries += 1
        needed_right = subtract_syndromes(target, left.contribution, modulus)
        right = right_table.get(needed_right)
        if right is not None:
            solution_count_lower_bound += 1
            recovered = (
                left.left_index,
                left.right_index,
                right.left_index,
                right.right_index,
            ) == true_indices
            return DecodeResult(
                selector,
                sum(len(values) for values in candidate_lists),
                merge_entries,
                rounds,
                recovered,
                solution_count_lower_bound,
            )
        left_table.setdefault(left.contribution, left)

        try:
            right = next(right_generator)
        except StopIteration:
            break
        merge_entries += 1
        needed_left = subtract_syndromes(target, right.contribution, modulus)
        left = left_table.get(needed_left)
        if left is not None:
            solution_count_lower_bound += 1
            recovered = (
                left.left_index,
                left.right_index,
                right.left_index,
                right.right_index,
            ) == true_indices
            return DecodeResult(
                selector,
                sum(len(values) for values in candidate_lists),
                merge_entries,
                rounds,
                recovered,
                solution_count_lower_bound,
            )
        right_table.setdefault(right.contribution, right)
    raise RuntimeError("meet-in-the-middle decoder exhausted both pair lists")


def one_trial(
    trial: int,
    candidates: tuple[Candidate, ...],
    polys: int,
    weight: int,
    block_length: int,
    modulus: int,
    channel: LeakageChannel,
    pair_slope: float,
    seed: int,
) -> tuple[TrialResult, ...]:
    rng = random.Random(seed)
    known = tuple(rng.randrange(block_length) for _ in range(polys * weight))
    true_indices = tuple(rng.randrange(len(candidates)) for _ in range(polys))
    true_candidates = tuple(candidates[index] for index in true_indices)
    width = weight * block_length
    multipliers = tuple(
        tuple(rng.randrange(modulus) for _ in range(width))
        for _ in range(polys - 1)
    )
    lists_by_hidden = tuple(
        support_lists_one_unknown(known, hidden, polys, weight)
        for hidden in true_candidates
    )
    true_lists = tuple(
        lists_by_hidden[hidden][known_poly * weight + output]
        for known_poly in range(polys)
        for hidden in range(polys)
        for output in range(weight)
    )
    descriptors = tuple(
        channel.sample(active, 2 * block_length, rng)
        for active in true_lists
    )
    candidate_lists = build_candidate_lists(
        candidates,
        known,
        descriptors,
        multipliers,
        polys,
        weight,
        block_length,
        modulus,
        channel,
        pair_slope,
    )
    target = bytes([0] * width)
    for polynomial, candidate in enumerate(true_candidates):
        target = add_syndromes(
            target,
            polynomial_contribution(
                candidate,
                polynomial,
                multipliers,
                block_length,
                modulus,
            ),
            modulus,
        )
    results = []
    for selector_index, selector in enumerate(("uniform", "pair", "exact")):
        decoded = decode_lists(
            candidate_lists,
            target,
            true_indices,
            selector,
            modulus,
            random.Random(seed ^ (selector_index << 40) ^ 0x4C495354),
        )
        results.append(
            # Uniform ordering evaluates no leakage likelihood.  The weighted
            # variants evaluate P*t descriptors for every candidate in each
            # of P polynomial lists.  Counting each complete descriptor
            # evaluation as one pair-entry operation is deliberately simple
            # and conservative at these dimensions.
            TrialResult(
                trial=trial,
                selector=selector,
                candidate_scores=decoded.candidate_scores,
                merge_entries=decoded.merge_entries,
                rounds=decoded.rounds,
                optimistic_work=decoded.optimistic_work,
                leakage_factor_evaluations=(
                    0
                    if selector == "uniform"
                    else decoded.candidate_scores * polys * weight
                ),
                factor_charged_work=(
                    decoded.optimistic_work
                    + (
                        0
                        if selector == "uniform"
                        else decoded.candidate_scores * polys * weight
                    )
                ),
                recovered_planted=int(decoded.recovered_planted),
                solution_count_lower_bound=decoded.solution_count_lower_bound,
            )
        )
    return tuple(results)


def geometric_mean(values: list[int]) -> float:
    return 2.0 ** statistics.fmean(math.log2(value) for value in values)


def paired_bootstrap_gain_interval(
    baseline: list[int],
    selected: list[int],
    samples: int,
    rng: random.Random,
) -> tuple[float, float]:
    if len(baseline) != len(selected) or not baseline:
        raise ValueError("paired bootstrap inputs must have equal positive size")
    gains = []
    for _ in range(samples):
        indices = [rng.randrange(len(baseline)) for _ in baseline]
        baseline_mean = statistics.fmean(baseline[index] for index in indices)
        selected_mean = statistics.fmean(selected[index] for index in indices)
        gains.append(math.log2(baseline_mean / selected_mean))
    gains.sort()
    lower = gains[math.floor(0.025 * (samples - 1))]
    upper = gains[math.ceil(0.975 * (samples - 1))]
    return lower, upper


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--polys", type=int, default=4)
    parser.add_argument("--weight", type=int, default=3)
    parser.add_argument("--block-length", type=int, default=8)
    parser.add_argument("--modulus", type=int, default=17)
    parser.add_argument("--partition-size", type=int)
    parser.add_argument("--selector-k", type=int, default=1)
    parser.add_argument("--trials", type=int, default=16)
    parser.add_argument("--pair-fit-samples", type=int, default=5000)
    parser.add_argument("--bootstrap-samples", type=int, default=5000)
    parser.add_argument("--seed", type=int, default=20260810)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.polys != 4:
        parser.error("the first list decoder requires P=4")
    if not 2 <= args.modulus <= 256:
        parser.error("the byte-packed syndrome modulus must lie in [2,256]")
    if min(
        args.weight,
        args.block_length,
        args.trials,
        args.bootstrap_samples,
    ) < 1:
        parser.error("dimensions, trials, and bootstrap samples must be positive")
    partition_size = args.partition_size or args.weight
    channel = LeakageChannel.build(
        "occupancy",
        args.selector_k,
        args.weight,
        partition_size,
    )
    pair_slope, pair_r_squared = fit_pair_slope(
        channel,
        args.weight,
        args.pair_fit_samples,
        random.Random(args.seed ^ 0xA5A5A5A5),
    )
    candidates = tuple(
        itertools.product(range(args.block_length), repeat=args.weight)
    )
    start = time.perf_counter()
    rows = [
        result
        for trial in range(args.trials)
        for result in one_trial(
            trial,
            candidates,
            args.polys,
            args.weight,
            args.block_length,
            args.modulus,
            channel,
            pair_slope,
            args.seed + trial,
        )
    ]
    seconds = time.perf_counter() - start
    by_selector = {
        selector: [row for row in rows if row.selector == selector]
        for selector in ("uniform", "pair", "exact")
    }
    baseline_merge = geometric_mean(
        [row.merge_entries for row in by_selector["uniform"]]
    )
    baseline_work = geometric_mean(
        [row.optimistic_work for row in by_selector["uniform"]]
    )
    baseline_expected_merge = statistics.fmean(
        row.merge_entries for row in by_selector["uniform"]
    )
    baseline_expected_work = statistics.fmean(
        row.optimistic_work for row in by_selector["uniform"]
    )
    baseline_charged_work = statistics.fmean(
        row.factor_charged_work for row in by_selector["uniform"]
    )
    baseline_charged_rows = [
        row.factor_charged_work for row in by_selector["uniform"]
    ]
    print(
        f"polys={args.polys} weight={args.weight} "
        f"block_length={args.block_length} modulus={args.modulus} "
        f"K={args.selector_k} candidates_per_poly={len(candidates)} "
        f"pair_slope={pair_slope} pair_r_squared={pair_r_squared} "
        f"trials={args.trials} seconds={seconds} seed={args.seed}"
    )
    for selector, selected_rows in by_selector.items():
        merge = geometric_mean([row.merge_entries for row in selected_rows])
        work = geometric_mean([row.optimistic_work for row in selected_rows])
        expected_merge = statistics.fmean(
            row.merge_entries for row in selected_rows
        )
        expected_work = statistics.fmean(
            row.optimistic_work for row in selected_rows
        )
        charged_work = statistics.fmean(
            row.factor_charged_work for row in selected_rows
        )
        charged_interval = paired_bootstrap_gain_interval(
            baseline_charged_rows,
            [row.factor_charged_work for row in selected_rows],
            args.bootstrap_samples,
            random.Random(
                args.seed
                ^ {"uniform": 0, "pair": 1, "exact": 2}[selector]
                ^ 0x424F4F54
            ),
        )
        print(
            f"selector={selector} merge_geomean={merge} "
            f"merge_gain_bits={math.log2(baseline_merge / merge)} "
            f"merge_mean={expected_merge} "
            f"merge_expected_gain_bits="
            f"{math.log2(baseline_expected_merge / expected_merge)} "
            f"work_geomean={work} "
            f"work_gain_bits={math.log2(baseline_work / work)} "
            f"work_mean={expected_work} "
            f"work_expected_gain_bits="
            f"{math.log2(baseline_expected_work / expected_work)} "
            f"factor_charged_work_mean={charged_work} "
            f"factor_charged_gain_bits="
            f"{math.log2(baseline_charged_work / charged_work)} "
            f"factor_charged_gain_ci95="
            f"[{charged_interval[0]},{charged_interval[1]}] "
            f"planted_recovery={sum(row.recovered_planted for row in selected_rows)}"
            f"/{len(selected_rows)}"
        )
    if args.output:
        fields = tuple(TrialResult.__dataclass_fields__)
        with args.output.open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=fields)
            writer.writeheader()
            for row in rows:
                writer.writerow(
                    {field: getattr(row, field) for field in fields}
                )
        print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
